// Writes js/src/dates/locales.js from src/genro_toolbox/dates/locales/*.json.
// Run after any change to the Python vocabulary: node js/scripts/build-locales.js
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';

const source = new URL('../../src/genro_toolbox/dates/locales/', import.meta.url);
const target = new URL('../src/dates/locales.js', import.meta.url);

const locales = {};
for (const file of readdirSync(source).filter(name => name.endsWith('.json')).sort()) {
    locales[file.slice(0, -'.json'.length)] = JSON.parse(readFileSync(new URL(file, source), 'utf8'));
}

writeFileSync(target, `// Copyright 2026 Softwell S.r.l. - Genro Team
// SPDX-License-Identifier: Apache-2.0
// Generated by js/scripts/build-locales.js from src/genro_toolbox/dates/locales/*.json.
// Do not edit: change the JSON files and run the script again.
export const locales = ${JSON.stringify(locales, null, 4)};
`);
